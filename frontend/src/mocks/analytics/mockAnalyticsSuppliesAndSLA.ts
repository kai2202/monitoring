export function getMockPrinterConsumablesOverview(): PrinterConsumablesOverview[] {
  return MOCK_PRINTER_DEFINITIONS.map((p) => {
    const totalMonthlyVolume = p.base30Days.reduce((a, b) => a + b, 0);
    let fuserLife = Math.min(100, Math.max(14, p.drumLife + ((p.ppmNominal % 7) - 3) * 4));
    if (p.id === 'prt-018') fuserLife = 14;
    if (p.id === 'prt-003') fuserLife = 48;

    return {
      printerId: p.id,
      printerName: p.name,
      model: p.model,
      floor: p.floorName,
      floorId: p.floorId,
      department: p.department,
      totalMonthlyVolume,
      tonerK: p.tonerK,
      tonerC: p.tonerC,
      tonerM: p.tonerM,
      tonerY: p.tonerY,
      drumLife: p.drumLife,
      fuserLife,
      wasteToner: p.wasteToner,
    };
  }).sort((a, b) => b.totalMonthlyVolume - a.totalMonthlyVolume);
}

